'use strict';

// MeetingJoinerStore factory. Returns the adapter selected by
// MEETING_JOINER_DB_DRIVER. Defaults to 'prisma' so the monorepo
// behaviour is byte-identical on day one; standalone deployments
// flip the env var to 'pg' and lose the core/ dependency entirely.

const DRIVERS = Object.freeze(['prisma', 'pg']);
const DEFAULT_DRIVER = 'prisma';

let cached = null;

function createStore(driverOverride = null) {
  const driver = String(
    driverOverride || process.env.MEETING_JOINER_DB_DRIVER || DEFAULT_DRIVER
  ).toLowerCase();

  if (!DRIVERS.includes(driver)) {
    throw new Error(
      `unknown MEETING_JOINER_DB_DRIVER: ${driver}; expected one of ${DRIVERS.join(', ')}`
    );
  }

  if (driver === 'prisma' && process.env.MEETING_JOINER_SCHEMA) {
    throw new Error(
      'MEETING_JOINER_SCHEMA requires MEETING_JOINER_DB_DRIVER=pg; ' +
      'the Prisma adapter is bound to the schema generated by core Prisma migrations'
    );
  }

  if (driver === 'pg') return require('./pgStore');
  return require('./prismaStore');
}

function getStore() {
  if (!cached) cached = createStore();
  return cached;
}

// Test-only — drop the cached singleton so a re-import picks up a new
// MEETING_JOINER_DB_DRIVER value.
function _resetForTests() {
  cached = null;
}

module.exports = { getStore, createStore, _resetForTests, DRIVERS, DEFAULT_DRIVER };
