"""MeetingJoinerStore Protocol + driver factory.

Selects the adapter via ``MEETING_JOINER_DB_DRIVER``. Defaults to
``prisma`` so monorepo behaviour is byte-identical; standalone
deployments set ``MEETING_JOINER_DB_DRIVER=pg``.
"""

from __future__ import annotations

import os
from types import ModuleType
from typing import Any, Optional, Protocol, runtime_checkable

DRIVERS: tuple[str, ...] = ("prisma", "pg")
DEFAULT_DRIVER = "prisma"


@runtime_checkable
class MeetingJoinerStore(Protocol):
    async def connect(self) -> None: ...
    async def disconnect(self) -> None: ...
    async def find_existing_ongoing(
        self, normalized_url: str, org_id: Optional[str] = None
    ) -> Optional[Any]: ...
    async def create_meeting(self, **fields: Any) -> Any: ...
    async def get_meeting(self, meeting_id: str) -> Optional[Any]: ...
    async def get_meetings_by_ids(self, meeting_ids: list[str]) -> list[Any]: ...
    async def find_unique_with_relations(self, meeting_id: str) -> Optional[Any]: ...
    async def update_status(self, meeting_id: str, status: str, **extras: Any) -> Any: ...
    async def update_fields(self, meeting_id: str, fields: dict[str, Any]) -> Optional[Any]: ...
    async def update_transcript(self, meeting_id: str, transcript: Any) -> Optional[Any]: ...
    async def update_participants(self, meeting_id: str, participants: Any) -> Optional[Any]: ...
    async def get_active_meetings(self, org_id: Optional[str] = None) -> list[Any]: ...
    async def get_meetings_by_org(self, org_id: str, status: Optional[str] = None) -> list[Any]: ...
    async def list_meetings(
        self,
        where: Optional[dict[str, Any]] = None,
        order_by: str = "created_at DESC",
        limit: Optional[int] = None,
    ) -> list[Any]: ...
    async def count_meetings(self, where: Optional[dict[str, Any]] = None) -> int: ...
    async def set_video_link(self, meeting_id: str, link: str) -> Optional[Any]: ...
    async def claim_next_join_job(self) -> Optional[Any]: ...
    async def query_raw(self, sql: str, *params: Any) -> list[dict]: ...


_cached_module: Optional[ModuleType] = None


def _load_driver_module(driver: str) -> ModuleType:
    if driver == "pg":
        from . import pg_store  # noqa: PLC0415

        return pg_store
    if driver == "prisma":
        from . import prisma_store  # noqa: PLC0415

        return prisma_store
    raise ValueError(
        f"unknown MEETING_JOINER_DB_DRIVER: {driver}; expected one of {', '.join(DRIVERS)}"
    )


def create_store(driver_override: Optional[str] = None) -> ModuleType:
    driver = (
        driver_override
        or os.environ.get("MEETING_JOINER_DB_DRIVER")
        or DEFAULT_DRIVER
    ).lower()
    if driver not in DRIVERS:
        raise ValueError(
            f"unknown MEETING_JOINER_DB_DRIVER: {driver}; expected one of {', '.join(DRIVERS)}"
        )
    if driver == "prisma" and os.environ.get("MEETING_JOINER_SCHEMA"):
        raise ValueError(
            "MEETING_JOINER_SCHEMA requires MEETING_JOINER_DB_DRIVER=pg; "
            "the Prisma adapter is bound to the schema generated by core "
            "Prisma migrations"
        )
    return _load_driver_module(driver)


def get_store() -> ModuleType:
    global _cached_module
    if _cached_module is None:
        _cached_module = create_store()
    return _cached_module


def _reset_for_tests() -> None:
    global _cached_module
    _cached_module = None
